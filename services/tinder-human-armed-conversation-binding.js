/* ==================================================
TINDER HUMAN-ARMED CONVERSATION BINDING

This is a deliberately narrow server-side authority for the case where a
SAFE Tinder capture has no source-provided stable platform reference.  It
does not turn visible UI data into identity.  A human may create a durable,
device-scoped conversation association, then arm exactly one later capture.

The durable reference and the permit are generated by this service.  Neither
is accepted from a dashboard caller, returned in public results, or placed in
audit details.  Android / protocol delivery is intentionally not wired here.
================================================== */

const UUID_V4 = /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const SHA256_HEX = /^[a-f0-9]{64}$/;

export const HUMAN_ARMED_CONVERSATION_CHANNEL = Object.freeze({
  TINDER: "tinder",
  WHATSAPP: "whatsapp"
});

// These names describe a later dedicated foundation.  They deliberately do
// not extend or reinterpret the V2-only `contact_conversation_bindings`
// contract used for source-observed accessibility evidence.
